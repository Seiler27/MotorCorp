    /** Agrega la pantalla de un módulo al área de contenido. */
    public void agregarModulo(javax.swing.JPanel panel, String nombre) {
        pnlContenido.add(panel, nombre);
    }

    /** Muestra la pantalla del módulo indicado. */
    public void mostrarModulo(String nombre) {
        ((java.awt.CardLayout) pnlContenido.getLayout()).show(pnlContenido, nombre);
    }

    /** Resalta en naranja el botón del módulo abierto. */
    public void marcarActivo(javax.swing.JButton activo) {
        for (javax.swing.JButton boton : new javax.swing.JButton[]{btnInicio, btnClientes, btnCola,
                btnInventario, btnHistorial, btnPos, btnReportes}) {
            Estilos.marcarBotonMenu(boton, boton == activo);
        }
    }

