    /** Muestra la manito sobre los botones y aplica el estilo de tablas y tarjetas. */
    private void aplicarEstilos(javax.swing.JPanel tarjeta, javax.swing.JTable[] tablas, javax.swing.JButton[] botones) {
        Estilos.tarjeta(tarjeta);
        for (javax.swing.JTable t : tablas) {
            Estilos.tabla(t);
        }
        for (javax.swing.JButton b : botones) {
            Estilos.manito(b);
        }
    }

    /** Fecha elegida en un selector, como LocalDate. */
    public static java.time.LocalDate fecha(javax.swing.JSpinner selector) {
        return ((java.util.Date) selector.getValue()).toInstant()
                .atZone(java.time.ZoneId.systemDefault()).toLocalDate();
    }

    /** Coloca una fecha en un selector. */
    public static void ponerFecha(javax.swing.JSpinner selector, java.time.LocalDate fecha) {
        selector.setValue(java.util.Date.from(fecha.atStartOfDay(java.time.ZoneId.systemDefault()).toInstant()));
    }

