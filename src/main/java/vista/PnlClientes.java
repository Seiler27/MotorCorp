    /** Deja el formulario vacío para registrar un cliente nuevo. */
    public void limpiarFormulario() {
        for (javax.swing.JTextField campo : new javax.swing.JTextField[]{txtDni, txtCelular, txtNombres,
                txtApellidos, txtCorreo}) {
            campo.setText("");
        }
        limpiarMoto();
        tblClientes.clearSelection();
        txtDni.requestFocus();
    }

    /** Limpia solo los datos de la moto. */
    public void limpiarMoto() {
        txtPlaca.setText("");
        txtMarca.setText("");
        txtModelo.setText("");
        tblMotos.clearSelection();
    }

