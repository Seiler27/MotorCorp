    /** Muestra la manito sobre los botones y aplica el estilo de tablas y tarjetas. */
    private void aplicarEstilos(javax.swing.JPanel tarjeta, javax.swing.JTable[] tablas, javax.swing.JButton[] botones) {
        Estilos.tarjeta(tarjeta);
        for (javax.swing.JTable t : tablas) {
            Estilos.tabla(t);
        }
        for (javax.swing.JButton b : botones) {
            Estilos.manito(b);
        }
    }

    /** Limpia el formulario para registrar un producto nuevo. */
    public void limpiarFormulario() {
        cboCategoria.setSelectedIndex(0);
        txtNombre.setText("");
        txtStock.setText("");
        txtPrecio.setText("");
        spnReponer.setValue(1);
        tblProductos.clearSelection();
    }

    /** El mecánico solo consulta el inventario: se ocultan los controles de edición. */
    public void permitirEdicion(boolean permitir) {
        pnlProducto.setVisible(permitir);
    }

