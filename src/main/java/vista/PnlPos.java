    /** Muestra la manito sobre los botones y aplica el estilo de tablas y tarjetas. */
    private void aplicarEstilos(javax.swing.JPanel tarjeta, javax.swing.JTable[] tablas, javax.swing.JButton[] botones) {
        Estilos.tarjeta(tarjeta);
        for (javax.swing.JTable t : tablas) {
            Estilos.tabla(t);
        }
        for (javax.swing.JButton b : botones) {
            Estilos.manito(b);
        }
    }

    /** Activa o desactiva los controles de cobro (cuando no hay orden seleccionada). */
    public void habilitarCobro(boolean activo) {
        for (javax.swing.JComponent c : new javax.swing.JComponent[]{cboProductoPos, spnCantidadPos, btnAgregarProducto,
                txtManoObra, btnQuitarItem, btnVaciar, cboTipo, btnGenerar}) {
            c.setEnabled(activo);
        }
    }

